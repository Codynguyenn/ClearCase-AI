"""List the licences of ClearCase's direct dependencies, read from the installed package metadata (not from memory).

    backend/.venv/bin/python scripts/list_licenses.py > docs/dependency_licenses.md

Direct dependencies only: the packages named in backend/pyproject.toml and frontend/package.json, plus the two pretrained models. It does not
audit every transitive package; run a dedicated tool (for example pip-licenses, license-checker) before any commercial redistribution.
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL_CARD = ROOT / ".local" / "models" / "models--sentence-transformers--all-MiniLM-L6-v2" / "snapshots"


def python_licence(name: str) -> tuple[str, str]:
    meta = metadata.metadata(name)
    version = meta["Version"]
    if meta.get("License-Expression"):
        return version, meta["License-Expression"]
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier", []) if c.startswith("License ::")]
    text = (meta.get("License") or "").strip().splitlines()
    first = text[0] if text and len(text[0]) < 80 else ""
    return version, "; ".join(classifiers) or first or "not stated in the metadata"


def node_licence(name: str) -> tuple[str, str]:
    pkg = json.loads((ROOT / "frontend" / "node_modules" / name / "package.json").read_text(encoding="utf-8"))
    lic = pkg.get("license") or pkg.get("licenses") or "not stated"
    return pkg["version"], lic if isinstance(lic, str) else json.dumps(lic)


def model_card_licence() -> str:
    for card in MODEL_CARD.glob("*/README.md"):
        match = re.search(r"^license:\s*(.+)$", card.read_text(encoding="utf-8"), re.M)
        if match:
            return match.group(1).strip()
    return "model card not found locally (run scripts/download_models.sh)"


def main() -> None:
    project = tomllib.loads((ROOT / "backend" / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    py = sorted({re.split(r"[\[=<>~! ]", d, maxsplit=1)[0] for d in project["dependencies"]})
    package = json.loads((ROOT / "frontend" / "package.json").read_text(encoding="utf-8"))
    out = [
        "# Dependency licences", "",
        "Generated by `scripts/list_licenses.py` from the installed package metadata. **Direct dependencies only** (the packages named in "
        "`backend/pyproject.toml` and `frontend/package.json`, plus the two pretrained models); transitive packages are not audited here.", "",
        "## The one that shapes this repository", "",
        "**PyMuPDF is AGPL-3.0** (or a commercial licence from Artifex). ClearCase links to it, so this repository is licensed **AGPL-3.0** "
        "(`LICENSE`). The other direct dependencies below are permissive (MIT, BSD, Apache-2.0), which AGPL-3.0 can include. Anyone who offers "
        "a modified ClearCase as a network service must publish their source; a closed-source product would need the commercial PyMuPDF licence "
        "or another PDF library. See `docs/decisions.md` section 1.", "",
        "## Python (backend)", "", "| Package | Version | Licence (from metadata) |", "| --- | --- | --- |",
    ]
    for name in py:
        version, licence = python_licence(name)
        out.append(f"| {name} | {version} | {licence} |")
    out += ["", "## JavaScript (frontend)", "", "| Package | Version | Licence (from package.json) |", "| --- | --- | --- |"]
    for name in sorted({*package["dependencies"], *package["devDependencies"]}):
        version, licence = node_licence(name)
        out.append(f"| {name} | {version} | {licence} |")
    spacy_version, spacy_licence = python_licence("en_core_web_sm")
    out += [
        "", "## Pretrained models (downloaded once, never bundled in the repository)", "", "| Model | Version | Licence |", "| --- | --- | --- |",
        f"| spaCy `en_core_web_sm` (named-entity recognition) | {spacy_version} | {spacy_licence} |",
        f"| `sentence-transformers/all-MiniLM-L6-v2` (policy embeddings, pinned revision) | see `CLEARCASE_EMBEDDING_REVISION` | {model_card_licence()} (model card) |",
        "", "## Services run separately (not linked into the code)", "",
        "- **MongoDB Community Server 8.0** is licensed under the SSPL, a source-available licence. ClearCase talks to it over the network through the "
        "official driver and does not include or modify it; check the SSPL's terms before offering MongoDB itself as a hosted service.",
        "- **Hosted model provider (live mode only)**: governed by the provider's terms of service, not a software licence; excerpts are sent to it only "
        "after the user confirms.", "",
        "This is engineering documentation, not legal advice.",
    ]
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
