"""requirements.lock must stay consistent with pyproject.toml and keep its hand-maintained torch lines.

A plain `pip freeze` loses the CPU-only PyTorch markers, which would make Docker and CI download several GB of
CUDA packages. scripts/regenerate_lock.sh writes the lock correctly; these tests catch a lock that was edited or
regenerated by other means. They read two files and need no network.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
PYPROJECT = BACKEND / "pyproject.toml"
LOCK = BACKEND / "requirements.lock"


def _normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _pins(requirement_lines: list[str]) -> list[tuple[str, str, str]]:
    """(name, version, marker) for every `name==version[; marker]` line, extras and comments ignored."""
    found = []
    for raw in requirement_lines:
        line = raw.strip()
        if not line or line.startswith(("#", "-")):
            continue
        if " @ " in line:  # a wheel pinned by URL, e.g. the spaCy model: no version to compare
            found.append((_normalise(line.split(" @ ", 1)[0]), "direct-url", ""))
            continue
        requirement, _, marker = line.partition(";")
        match = re.match(r"^([A-Za-z0-9_.-]+)(?:\[[^\]]*\])?==(\S+)$", requirement.strip())
        assert match, f"not an exact pin: {line!r}"
        found.append((_normalise(match.group(1)), match.group(2), marker.strip()))
    return found


def lock_lines() -> list[str]:
    return LOCK.read_text(encoding="utf-8").splitlines()


def direct_requirements() -> list[str]:
    project = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))["project"]
    return project["dependencies"] + project.get("optional-dependencies", {}).get("dev", [])


def test_every_direct_dependency_is_pinned_exactly_in_the_lock():
    locked = {}
    for name, version, _marker in _pins(lock_lines()):
        locked.setdefault(name, set()).add(version.split("+")[0])  # torch: "2.14.1" and "2.14.1+cpu" are one release
    for name, version, _ in _pins(direct_requirements()):
        assert name in locked, f"{name} is in pyproject.toml but missing from requirements.lock"
        assert locked[name] == {version}, f"{name}: pyproject pins {version}, the lock has {sorted(locked[name])}"


def test_the_lock_has_no_duplicate_pins_except_torch_platform_variants():
    names = [name for name, _, _ in _pins(lock_lines())]
    duplicates = {n for n in names if names.count(n) > 1}
    assert duplicates <= {"torch"}, f"duplicate pins: {sorted(duplicates - {'torch'})}"


def test_torch_has_one_pin_per_platform_and_the_cpu_index_is_declared():
    lines = lock_lines()
    assert "--extra-index-url https://download.pytorch.org/whl/cpu" in lines
    torch = [(version, marker) for name, version, marker in _pins(lines) if name == "torch"]
    assert len(torch) == 2, f"expected a macOS and a Linux torch line, found {torch}"
    by_marker = {marker: version for version, marker in torch}
    assert set(by_marker) == {'sys_platform == "darwin"', 'sys_platform == "linux"'}
    mac, linux = by_marker['sys_platform == "darwin"'], by_marker['sys_platform == "linux"']
    assert linux == f"{mac}+cpu", "Linux must get the CPU-only build of the same release"


def test_the_spacy_model_is_pinned_to_an_exact_wheel_with_a_hash():
    # The NER model is not on PyPI; the lock pins the wheel by URL and sha256 so every install gets the same bytes.
    model = [line for line in lock_lines() if line.startswith("en_core_web_sm @ ")]
    assert len(model) == 1
    assert re.search(r"/en_core_web_sm-\d+\.\d+\.\d+-py3-none-any\.whl#sha256=[0-9a-f]{64}$", model[0])
